/**
 * Returns today's curated pearl based on current UTC day of month (1 to 31).
 */
export function getTodayCuratedPearl(): DailyPearl {
  const day = new Date().getUTCDate();
  const found = DAILY_PEARLS.find((p) => p.day === day);
  return found || DAILY_PEARLS[0];
}
